void solve(){
    string s, s1, s2; cin >> s >> s1 >> s2;

    int n = len(s), n1 = len(s1), n2 = len(s2);
    vvec<int> dp(n1 + 1, n2 + 1, -1);
    auto func = [&](auto func, int i, int i1, int i2) -> bool {
        if(i == n) return true;

        int &res = dp[i1][i2];
        if(res != -1) return res;

        res = false;
        if(i1 < n1 && s[i] == s1[i1]) res |= func(func, i + 1, i1 + 1, i2);
        if(i2 < n2 && s[i] == s2[i2]) res |= func(func, i + 1, i1, i2 + 1);
        return res;
    };

    cout << (func(func, 0, 0, 0) ? "yes" : "no");
}

